import React, { useEffect, useMemo, useState } from 'react';
import {
  Plus,
  Truck,
  Building2,
  CheckCircle2,
  Trash2,
  Pencil,
  Search,
  Eye,
  DollarSign,
  Upload,
} from 'lucide-react';
import { PurchaseOrder, PurchaseOrderItem, Supplier } from '../../types';
import { useStore } from '../../context/StoreContext';
import { formatCurrency, formatDateShort, roundMoney } from '../../utils/format';
import { tr, translatePOStatus } from '../../utils/i18n';
import { Modal } from '../ui/Modal';
import { DataImportModal } from '../ui/DataImportModal';

const EMPTY_SUPPLIER = {
  id: undefined as string | undefined,
  name: '',
  contactPerson: '',
  phone: '',
  email: '',
  address: '',
  balanceOwed: '0',
  customFields: {} as Record<string, string>,
};

export const PurchasesModule: React.FC = () => {
  const {
    state,
    pendingRestockProductId,
    setPendingRestockProductId,
    pendingRestockBatch,
    setPendingRestockBatch,
    saveSupplier,
    recordSupplierPayment,
    createPurchaseOrder,
    receivePurchaseOrder,
  } = useStore();
  const sym = state.settings.currencySymbol;
  const lang = state.settings.language;
  const supplierSchema = state.moduleSchemas.suppliers ?? [];
  const purchaseSchema = state.moduleSchemas.purchases ?? [];

  const [activeTab, setActiveTab] = useState<'orders' | 'suppliers'>('orders');
  const [poStatusFilter, setPoStatusFilter] = useState<'all' | 'Pending' | 'Received'>('all');
  const [search, setSearch] = useState('');
  const [importModalOpen, setImportModalOpen] = useState(false);

  // Create PO Modal
  const [poModalOpen, setPoModalOpen] = useState(false);
  const [poSupplierId, setPoSupplierId] = useState(state.suppliers[0]?.id ?? '');
  const [poItems, setPoItems] = useState<PurchaseOrderItem[]>([]);
  const [poNotes, setPoNotes] = useState('');
  const [poCustomFields, setPoCustomFields] = useState<Record<string, string>>({});
  const [viewPO, setViewPO] = useState<PurchaseOrder | null>(null);

  // Supplier Modal
  const [supplierModalOpen, setSupplierModalOpen] = useState(false);
  const [supplierForm, setSupplierForm] = useState(EMPTY_SUPPLIER);

  // Supplier Payment Modal
  const [paySupplierTarget, setPaySupplierTarget] = useState<Supplier | null>(null);
  const [paySupplierAmount, setPaySupplierAmount] = useState('');

  // Handle single-item Restock Shortcut from Dashboard
  useEffect(() => {
    if (!pendingRestockProductId) return;
    const product = state.products.find((p) => p.id === pendingRestockProductId);
    if (product) {
      const suggestedQty = Math.max(10, product.reorderLevel * 2 - product.stock);
      setActiveTab('orders');
      setPoSupplierId(state.suppliers[0]?.id ?? '');
      setPoItems([
        {
          productId: product.id,
          productName: product.name,
          sku: product.sku,
          quantity: suggestedQty,
          unitCost: product.costPrice,
        },
      ]);
      setPoNotes(
        tr(
          lang,
          `Restock triggered from low-stock alert for ${product.sku}.`,
          `إعادة توريد بناءً على تنبيه انخفاض المخزون للصنف ${product.sku}.`
        )
      );
      setPoCustomFields({});
      setPoModalOpen(true);
    }
    setPendingRestockProductId(null);
  }, [pendingRestockProductId, state.products, state.suppliers, setPendingRestockProductId, lang]);

  // Handle multi-SKU EOQ Batch Restock from Decision Engine
  useEffect(() => {
    if (!pendingRestockBatch || pendingRestockBatch.length === 0) return;
    setActiveTab('orders');
    setPoSupplierId(state.suppliers[0]?.id ?? '');
    setPoItems(pendingRestockBatch);
    setPoNotes(
      tr(
        lang,
        'Generated by Decision Engine using EOQ & 95% Safety Stock ROP.',
        'تم توليده بواسطة محرك القرارات باستخدام نموذج EOQ ومخزون الأمان 95%.'
      )
    );
    setPoCustomFields({});
    setPoModalOpen(true);
    setPendingRestockBatch(null);
  }, [pendingRestockBatch, state.suppliers, setPendingRestockBatch, lang]);

  const stats = useMemo(() => {
    const pendingPOs = state.purchaseOrders.filter((p) => p.status === 'Pending');
    const receivedPOs = state.purchaseOrders.filter((p) => p.status === 'Received');
    const totalOwed = state.suppliers.reduce((sum, s) => sum + s.balanceOwed, 0);
    const pendingValue = pendingPOs.reduce((sum, p) => sum + p.totalCost, 0);
    return {
      pendingCount: pendingPOs.length,
      receivedCount: receivedPOs.length,
      pendingValue,
      totalOwed,
    };
  }, [state.purchaseOrders, state.suppliers]);

  const filteredPOs = useMemo(() => {
    const q = search.trim().toLowerCase();
    return state.purchaseOrders.filter((po) => {
      if (poStatusFilter !== 'all' && po.status !== poStatusFilter) return false;
      if (!q) return true;
      return (
        po.poNumber.toLowerCase().includes(q) ||
        po.supplierName.toLowerCase().includes(q) ||
        po.items.some((i) => i.productName.toLowerCase().includes(q))
      );
    });
  }, [state.purchaseOrders, poStatusFilter, search]);

  const filteredSuppliers = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return state.suppliers;
    return state.suppliers.filter(
      (s) =>
        s.name.toLowerCase().includes(q) ||
        s.contactPerson.toLowerCase().includes(q) ||
        s.email.toLowerCase().includes(q)
    );
  }, [state.suppliers, search]);

  const openCreatePO = () => {
    const defaultProd = state.products[0];
    setPoSupplierId(state.suppliers[0]?.id ?? '');
    setPoItems(
      defaultProd
        ? [
            {
              productId: defaultProd.id,
              productName: defaultProd.name,
              sku: defaultProd.sku,
              quantity: 10,
              unitCost: defaultProd.costPrice,
            },
          ]
        : []
    );
    setPoNotes('');
    setPoCustomFields({});
    setPoModalOpen(true);
  };

  const addPORow = () => {
    const unused =
      state.products.find((p) => !poItems.some((item) => item.productId === p.id)) ??
      state.products[0];
    if (!unused) return;
    setPoItems((prev) => [
      ...prev,
      {
        productId: unused.id,
        productName: unused.name,
        sku: unused.sku,
        quantity: 10,
        unitCost: unused.costPrice,
      },
    ]);
  };

  const updatePORowProduct = (index: number, productId: string) => {
    const prod = state.products.find((p) => p.id === productId);
    if (!prod) return;
    setPoItems((prev) =>
      prev.map((row, idx) =>
        idx === index
          ? {
              ...row,
              productId: prod.id,
              productName: prod.name,
              sku: prod.sku,
              unitCost: prod.costPrice,
            }
          : row
      )
    );
  };

  const updatePORowField = (index: number, field: 'quantity' | 'unitCost', value: number) => {
    setPoItems((prev) =>
      prev.map((row, idx) =>
        idx === index ? { ...row, [field]: Math.max(0, Number.isFinite(value) ? value : 0) } : row
      )
    );
  };

  const removePORow = (index: number) => {
    setPoItems((prev) => prev.filter((_, idx) => idx !== index));
  };

  const poTotalCost = roundMoney(
    poItems.reduce((sum, item) => sum + item.quantity * item.unitCost, 0)
  );

  const handleSubmitPO = (markReceivedImmediately: boolean) => {
    const validItems = poItems.filter((i) => i.quantity > 0);
    if (!poSupplierId || validItems.length === 0) return;
    createPurchaseOrder({
      supplierId: poSupplierId,
      items: validItems,
      notes: poNotes,
      markReceivedImmediately,
      customFields: poCustomFields,
    });
    setPoModalOpen(false);
  };

  const openAddSupplier = () => {
    setSupplierForm({ ...EMPTY_SUPPLIER, customFields: {} });
    setSupplierModalOpen(true);
  };

  const openEditSupplier = (supplier: Supplier) => {
    setSupplierForm({
      id: supplier.id,
      name: supplier.name,
      contactPerson: supplier.contactPerson,
      phone: supplier.phone,
      email: supplier.email,
      address: supplier.address,
      balanceOwed: supplier.balanceOwed.toString(),
      customFields: { ...(supplier.customFields ?? {}) },
    });
    setSupplierModalOpen(true);
  };

  const handleSaveSupplier = (e: React.FormEvent) => {
    e.preventDefault();
    if (!supplierForm.name.trim()) return;
    saveSupplier({
      id: supplierForm.id,
      name: supplierForm.name.trim(),
      contactPerson: supplierForm.contactPerson.trim(),
      phone: supplierForm.phone.trim(),
      email: supplierForm.email.trim(),
      address: supplierForm.address.trim(),
      balanceOwed: Math.max(0, parseFloat(supplierForm.balanceOwed) || 0),
      customFields: supplierForm.customFields,
    });
    setSupplierModalOpen(false);
  };

  const handleRecordSupplierPay = (e: React.FormEvent) => {
    e.preventDefault();
    if (!paySupplierTarget) return;
    const amt = parseFloat(paySupplierAmount) || 0;
    if (amt <= 0) return;
    recordSupplierPayment(paySupplierTarget.id, amt);
    setPaySupplierTarget(null);
  };

  return (
    <div className="space-y-5">
      {/* KPI Strip */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="bg-white border border-slate-200/85 rounded-xl p-4 shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <p className="text-xs text-slate-500 font-medium">
            {tr(lang, 'Pending POs', 'أوامر شراء قيد الانتظار')}
          </p>
          <p className="text-xl font-bold font-mono text-amber-600 tabular-nums mt-1.5">
            {stats.pendingCount}
          </p>
        </div>
        <div className="bg-white border border-slate-200/85 rounded-xl p-4 shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <p className="text-xs text-slate-500 font-medium">
            {tr(lang, 'Incoming Order Value', 'قيمة التوريدات الواردة')}
          </p>
          <p className="text-xl font-bold font-mono text-slate-900 tabular-nums mt-1.5">
            {formatCurrency(stats.pendingValue, sym)}
          </p>
        </div>
        <div className="bg-white border border-slate-200/85 rounded-xl p-4 shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <p className="text-xs text-slate-500 font-medium">
            {tr(lang, 'Received POs', 'أوامر شراء مستلمة')}
          </p>
          <p className="text-xl font-bold font-mono text-emerald-700 tabular-nums mt-1.5">
            {stats.receivedCount}
          </p>
        </div>
        <div className="bg-white border border-slate-200/85 rounded-xl p-4 shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <p className="text-xs text-slate-500 font-medium">
            {tr(lang, 'Supplier Balance Owed', 'مستحقات الموردين')}
          </p>
          <p className="text-xl font-bold font-mono text-slate-900 tabular-nums mt-1.5">
            {formatCurrency(stats.totalOwed, sym)}
          </p>
        </div>
      </div>

      {/* Sub-tabs & Primary CTAs */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="inline-flex items-center p-1 bg-slate-200/75 rounded-lg">
          <button
            type="button"
            onClick={() => setActiveTab('orders')}
            className={`inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 ${
              activeTab === 'orders'
                ? 'bg-white text-slate-900 shadow-sm'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Truck className="w-3.5 h-3.5" />
            {tr(lang, 'Purchase Orders', 'أوامر الشراء')} ({state.purchaseOrders.length})
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('suppliers')}
            className={`inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 ${
              activeTab === 'suppliers'
                ? 'bg-white text-slate-900 shadow-sm'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Building2 className="w-3.5 h-3.5" />
            {tr(lang, 'Supplier Directory', 'دليل الموردين')} ({state.suppliers.length})
          </button>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={() => setImportModalOpen(true)}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200/85 hover:bg-slate-50 rounded-lg transition-colors whitespace-nowrap shrink-0"
          >
            <Upload className="w-3.5 h-3.5" />
            {tr(lang, 'Import / Format', 'استيراد / تنسيق')}
          </button>
          <button
            type="button"
            onClick={openAddSupplier}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200/85 hover:bg-slate-50 rounded-lg transition-colors whitespace-nowrap shrink-0"
          >
            <Plus className="w-3.5 h-3.5" />
            {tr(lang, 'Add Supplier', 'إضافة مورد')}
          </button>
          <button
            type="button"
            onClick={openCreatePO}
            disabled={state.suppliers.length === 0 || state.products.length === 0}
            className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-teal-700 hover:bg-teal-800 disabled:bg-slate-300 rounded-lg transition-colors whitespace-nowrap shrink-0 shadow-xs"
          >
            <Plus className="w-3.5 h-3.5" />
            {tr(lang, 'Create Purchase Order', 'إنشاء أمر شراء')}
          </button>
        </div>
      </div>

      {/* Purchase Orders View */}
      {activeTab === 'orders' ? (
        <div className="bg-white border border-slate-200/85 rounded-xl overflow-hidden shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <div className="p-4 border-b border-slate-200/80 flex flex-wrap items-center gap-3">
            <div className="relative flex-1 min-w-[220px]">
              <Search className="w-4 h-4 text-slate-400 absolute start-3 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder={tr(
                  lang,
                  'Search PO number, supplier, or product...',
                  'ابحث برقم أمر الشراء أو المورد أو الصنف...'
                )}
                className="w-full ps-9 pe-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-lg focus:outline-none focus:bg-white focus:border-teal-600"
              />
            </div>

            <div className="inline-flex items-center p-0.5 bg-slate-100 rounded-lg">
              {(['all', 'Pending', 'Received'] as const).map((status) => (
                <button
                  key={status}
                  type="button"
                  onClick={() => setPoStatusFilter(status)}
                  className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 ${
                    poStatusFilter === status
                      ? 'bg-white text-slate-900 shadow-sm'
                      : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  {status === 'all'
                    ? tr(lang, 'All Orders', 'كل الأوامر')
                    : translatePOStatus(status, lang)}
                </button>
              ))}
            </div>
          </div>

          <div className="overflow-x-auto">
            {filteredPOs.length === 0 ? (
              <div className="p-10 text-center text-sm text-slate-500">
                {tr(lang, 'No purchase orders found.', 'لا توجد أوامر شراء مطابقة.')}
              </div>
            ) : (
              <table className="w-full text-start border-collapse">
                <thead>
                  <tr className="border-b border-slate-200 bg-slate-50/80 text-xs font-medium text-slate-500">
                    <th className="py-3 px-4 text-start">
                      {tr(lang, 'PO Number', 'رقم أمر الشراء')}
                    </th>
                    <th className="py-3 px-4 text-start">{tr(lang, 'Supplier', 'المورد')}</th>
                    <th className="py-3 px-4 text-start">{tr(lang, 'Date', 'التاريخ')}</th>
                    <th className="py-3 px-4 text-start">{tr(lang, 'Items', 'الأصناف')}</th>
                    <th className="py-3 px-4 text-end">
                      {tr(lang, 'Total Cost', 'إجمالي التكلفة')}
                    </th>
                    <th className="py-3 px-4 text-start">{tr(lang, 'Status', 'الحالة')}</th>
                    <th className="py-3 px-4 text-end">{tr(lang, 'Actions', 'إجراءات')}</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 text-xs">
                  {filteredPOs.map((po) => (
                    <tr key={po.id} className="hover:bg-slate-50/75 transition-colors">
                      <td className="py-3 px-4 font-mono font-semibold text-slate-900 whitespace-nowrap">
                        {po.poNumber}
                      </td>
                      <td className="py-3 px-4 font-medium text-slate-800">{po.supplierName}</td>
                      <td className="py-3 px-4 text-slate-500 whitespace-nowrap tabular-nums">
                        {formatDateShort(po.date, lang)}
                      </td>
                      <td className="py-3 px-4 text-slate-600 max-w-xs truncate">
                        {po.items.map((i) => `${i.quantity}× ${i.productName}`).join('، ')}
                      </td>
                      <td className="py-3 px-4 text-end font-mono font-semibold text-slate-900 tabular-nums whitespace-nowrap">
                        {formatCurrency(po.totalCost, sym)}
                      </td>
                      <td className="py-3 px-4 whitespace-nowrap">
                        <span
                          className={`font-semibold text-xs ${
                            po.status === 'Received' ? 'text-emerald-700' : 'text-amber-700'
                          }`}
                        >
                          {translatePOStatus(po.status, lang)}
                        </span>
                      </td>
                      <td className="py-3 px-4 text-end whitespace-nowrap">
                        <div className="inline-flex items-center gap-1.5">
                          <button
                            type="button"
                            onClick={() => setViewPO(po)}
                            className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-medium text-slate-700 hover:bg-slate-100 rounded-md whitespace-nowrap"
                          >
                            <Eye className="w-3.5 h-3.5" />
                            {tr(lang, 'View', 'عرض')}
                          </button>
                          {po.status === 'Pending' && (
                            <button
                              type="button"
                              onClick={() => receivePurchaseOrder(po.id)}
                              className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-semibold text-emerald-800 bg-emerald-50 hover:bg-emerald-100 rounded-md transition-colors whitespace-nowrap"
                            >
                              <CheckCircle2 className="w-3.5 h-3.5" />
                              {tr(lang, 'Mark Received', 'تأكيد الاستلام')}
                            </button>
                          )}
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </div>
        </div>
      ) : (
        /* Supplier Directory */
        <div className="bg-white border border-slate-200/85 rounded-xl overflow-hidden shadow-[0_1px_2px_rgba(15,23,42,0.03)]">
          <div className="p-4 border-b border-slate-200/80">
            <div className="relative max-w-sm">
              <Search className="w-4 h-4 text-slate-400 absolute start-3 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder={tr(
                  lang,
                  'Search suppliers by name or contact...',
                  'ابحث عن مورد بالاسم أو جهة الاتصال...'
                )}
                className="w-full ps-9 pe-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-lg focus:outline-none focus:bg-white focus:border-teal-600"
              />
            </div>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-start border-collapse">
              <thead>
                <tr className="border-b border-slate-200 bg-slate-50/80 text-xs font-medium text-slate-500">
                  <th className="py-3 px-4 text-start">{tr(lang, 'Supplier', 'المورد')}</th>
                  <th className="py-3 px-4 text-start">{tr(lang, 'Contact', 'مسؤول التواصل')}</th>
                  <th className="py-3 px-4 text-start">
                    {tr(lang, 'Phone & Email', 'الهاتف والبريد الإلكتروني')}
                  </th>
                  {supplierSchema.slice(0, 2).map((cf) => (
                    <th key={cf.id} className="py-3 px-3 text-start whitespace-nowrap">
                      {cf.label}
                    </th>
                  ))}
                  <th className="py-3 px-4 text-end">
                    {tr(lang, 'Balance Owed', 'الرصيد المستحق')}
                  </th>
                  <th className="py-3 px-4 text-end">{tr(lang, 'Actions', 'إجراءات')}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 text-xs">
                {filteredSuppliers.map((sup) => (
                  <tr key={sup.id} className="hover:bg-slate-50/75 transition-colors">
                    <td className="py-3 px-4">
                      <div className="font-semibold text-slate-900 text-sm">{sup.name}</div>
                      <div className="text-[11px] text-slate-500">{sup.address}</div>
                    </td>
                    <td className="py-3 px-4 text-slate-700">{sup.contactPerson || '—'}</td>
                    <td className="py-3 px-4 text-slate-600">
                      <div dir="ltr" className="text-start">
                        {sup.phone || '—'}
                      </div>
                      <div className="text-[11px] text-slate-500">{sup.email}</div>
                    </td>
                    {supplierSchema.slice(0, 2).map((cf) => (
                      <td key={cf.id} className="py-3 px-3 text-slate-600 whitespace-nowrap">
                        {sup.customFields?.[cf.key] || '—'}
                      </td>
                    ))}
                    <td className="py-3 px-4 text-end font-mono font-semibold tabular-nums whitespace-nowrap">
                      <span className={sup.balanceOwed > 0 ? 'text-amber-700' : 'text-emerald-700'}>
                        {formatCurrency(sup.balanceOwed, sym)}
                      </span>
                    </td>
                    <td className="py-3 px-4 text-end whitespace-nowrap">
                      <div className="inline-flex items-center gap-1.5">
                        {sup.balanceOwed > 0 && (
                          <button
                            type="button"
                            onClick={() => {
                              setPaySupplierTarget(sup);
                              setPaySupplierAmount(sup.balanceOwed.toFixed(2));
                            }}
                            className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-medium text-teal-800 bg-teal-50 hover:bg-teal-100 rounded-md whitespace-nowrap"
                          >
                            <DollarSign className="w-3 h-3" />
                            {tr(lang, 'Pay', 'سداد')}
                          </button>
                        )}
                        <button
                          type="button"
                          onClick={() => openEditSupplier(sup)}
                          className="p-1.5 text-slate-500 hover:text-slate-900 hover:bg-slate-100 rounded"
                          aria-label={tr(lang, `Edit ${sup.name}`, `تعديل ${sup.name}`)}
                        >
                          <Pencil className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Create Purchase Order Modal */}
      <Modal
        open={poModalOpen}
        onClose={() => setPoModalOpen(false)}
        title={tr(lang, 'Create Purchase Order', 'إنشاء أمر شراء')}
        subtitle={tr(
          lang,
          'Select supplier and items to replenish stock and update weighted unit costs',
          'اختر المورد والأصناف لتغذية المخزون وتحديث تكاليف الوحدة تلقائياً'
        )}
        maxWidthClass="max-w-2xl"
        footer={
          <div className="w-full flex flex-wrap items-center justify-between gap-2">
            <div className="text-xs text-slate-600 tabular-nums">
              {tr(lang, 'Total Order Cost:', 'إجمالي تكلفة الأمر:')}{' '}
              <strong className="font-mono text-sm text-slate-900">
                {formatCurrency(poTotalCost, sym)}
              </strong>
            </div>
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => setPoModalOpen(false)}
                className="px-3.5 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg whitespace-nowrap"
              >
                {tr(lang, 'Cancel', 'إلغاء')}
              </button>
              <button
                type="button"
                disabled={poItems.length === 0 || !poSupplierId}
                onClick={() => handleSubmitPO(false)}
                className="px-3.5 py-2 text-xs font-medium text-slate-900 bg-slate-200 hover:bg-slate-300 disabled:opacity-50 rounded-lg whitespace-nowrap"
              >
                {tr(lang, 'Save as Pending', 'حفظ كقيد الانتظار')}
              </button>
              <button
                type="button"
                disabled={poItems.length === 0 || !poSupplierId}
                onClick={() => handleSubmitPO(true)}
                className="px-4 py-2 text-xs font-semibold text-white bg-teal-700 hover:bg-teal-800 disabled:opacity-50 rounded-lg whitespace-nowrap"
              >
                {tr(lang, 'Create & Mark Received', 'إنشاء واستلام فوري')}
              </button>
            </div>
          </div>
        }
      >
        <div className="space-y-4">
          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              {tr(lang, 'Supplier', 'المورد')}
            </label>
            <select
              value={poSupplierId}
              onChange={(e) => setPoSupplierId(e.target.value)}
              className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
            >
              {state.suppliers.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.name} ({s.contactPerson})
                </option>
              ))}
            </select>
          </div>

          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <label className="text-xs font-medium text-slate-700">
                {tr(lang, 'Order Line Items', 'بنود أمر الشراء')}
              </label>
              <button
                type="button"
                onClick={addPORow}
                className="inline-flex items-center gap-1 text-xs font-medium text-teal-700 hover:text-teal-900"
              >
                <Plus className="w-3.5 h-3.5" />
                {tr(lang, 'Add Line', 'إضافة بند')}
              </button>
            </div>

            <div className="border border-slate-200 rounded-lg divide-y divide-slate-200">
              {poItems.map((row, index) => (
                <div
                  key={`${row.productId}-${index}`}
                  className="p-3 grid grid-cols-1 sm:grid-cols-12 gap-2.5 items-end"
                >
                  <div className="sm:col-span-6">
                    <label className="block text-[11px] text-slate-500 mb-1">
                      {tr(lang, 'Product', 'الصنف')}
                    </label>
                    <select
                      value={row.productId}
                      onChange={(e) => updatePORowProduct(index, e.target.value)}
                      className="w-full px-2.5 py-1.5 text-xs bg-white border border-slate-300 rounded-md focus:outline-none focus:border-teal-600"
                    >
                      {state.products.map((p) => (
                        <option key={p.id} value={p.id}>
                          {p.sku} — {p.name} ({tr(lang, 'Stock', 'الرصيد')}: {p.stock})
                        </option>
                      ))}
                    </select>
                  </div>
                  <div className="sm:col-span-2">
                    <label className="block text-[11px] text-slate-500 mb-1">
                      {tr(lang, 'Qty', 'الكمية')}
                    </label>
                    <input
                      type="number"
                      min={1}
                      value={row.quantity}
                      onChange={(e) =>
                        updatePORowField(index, 'quantity', parseInt(e.target.value, 10) || 0)
                      }
                      className="w-full px-2.5 py-1.5 text-xs font-mono border border-slate-300 rounded-md"
                    />
                  </div>
                  <div className="sm:col-span-3">
                    <label className="block text-[11px] text-slate-500 mb-1">
                      {tr(lang, 'Unit Cost', 'تكلفة الوحدة')} ({sym.trim()})
                    </label>
                    <input
                      type="number"
                      min={0}
                      step="0.01"
                      value={row.unitCost}
                      onChange={(e) =>
                        updatePORowField(index, 'unitCost', parseFloat(e.target.value) || 0)
                      }
                      className="w-full px-2.5 py-1.5 text-xs font-mono border border-slate-300 rounded-md"
                    />
                  </div>
                  <div className="sm:col-span-1 flex justify-end">
                    <button
                      type="button"
                      onClick={() => removePORow(index)}
                      disabled={poItems.length <= 1}
                      className="p-1.5 text-slate-400 hover:text-red-600 disabled:opacity-30 rounded"
                      aria-label={tr(lang, 'Remove line', 'حذف البند')}
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>

          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              {tr(lang, 'Order Notes', 'ملاحظات الطلب')}
            </label>
            <input
              type="text"
              value={poNotes}
              onChange={(e) => setPoNotes(e.target.value)}
              placeholder={tr(
                lang,
                'Delivery instructions or supplier reference...',
                'تعليمات التسليم أو رقم مرجع المورد...'
              )}
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
            />
          </div>

          {purchaseSchema.length > 0 && (
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {purchaseSchema.map((cf) => (
                <div key={cf.id}>
                  <label className="block text-xs font-medium text-slate-700 mb-1">
                    {cf.label}
                  </label>
                  <input
                    type={cf.type}
                    value={poCustomFields[cf.key] ?? ''}
                    onChange={(e) =>
                      setPoCustomFields((prev) => ({ ...prev, [cf.key]: e.target.value }))
                    }
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
              ))}
            </div>
          )}
        </div>
      </Modal>

      {/* View PO Detail Modal */}
      <Modal
        open={Boolean(viewPO)}
        onClose={() => setViewPO(null)}
        title={viewPO ? `${viewPO.poNumber} · ${viewPO.supplierName}` : ''}
        subtitle={
          viewPO
            ? `${tr(lang, 'Ordered', 'تاريخ الطلب')} ${formatDateShort(viewPO.date, lang)}${
                viewPO.receivedDate
                  ? ` · ${tr(lang, 'Received', 'تاريخ الاستلام')} ${formatDateShort(
                      viewPO.receivedDate,
                      lang
                    )}`
                  : ''
              }`
            : ''
        }
        footer={
          <>
            <button
              type="button"
              onClick={() => setViewPO(null)}
              className="px-4 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg whitespace-nowrap"
            >
              {tr(lang, 'Close', 'إغلاق')}
            </button>
            {viewPO?.status === 'Pending' && (
              <button
                type="button"
                onClick={() => {
                  receivePurchaseOrder(viewPO.id);
                  setViewPO(null);
                }}
                className="px-4 py-2 text-xs font-semibold text-white bg-emerald-700 hover:bg-emerald-800 rounded-lg whitespace-nowrap"
              >
                {tr(lang, 'Mark as Received & Restock', 'تأكيد الاستلام وإضافة للمخزون')}
              </button>
            )}
          </>
        }
      >
        {viewPO && (
          <div className="space-y-4">
            <table className="w-full text-start text-xs border-collapse">
              <thead>
                <tr className="border-b border-slate-200 text-slate-500">
                  <th className="py-2 text-start">{tr(lang, 'Product', 'الصنف')}</th>
                  <th className="py-2 text-end">{tr(lang, 'Qty', 'الكمية')}</th>
                  <th className="py-2 text-end">{tr(lang, 'Unit Cost', 'تكلفة الوحدة')}</th>
                  <th className="py-2 text-end">{tr(lang, 'Subtotal', 'الإجمالي')}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {viewPO.items.map((item, i) => (
                  <tr key={i}>
                    <td className="py-2.5">
                      <div className="font-medium text-slate-900">{item.productName}</div>
                      <div className="font-mono text-[11px] text-slate-500">{item.sku}</div>
                    </td>
                    <td className="py-2.5 text-end font-mono tabular-nums">{item.quantity}</td>
                    <td className="py-2.5 text-end font-mono tabular-nums">
                      {formatCurrency(item.unitCost, sym)}
                    </td>
                    <td className="py-2.5 text-end font-mono font-semibold tabular-nums">
                      {formatCurrency(item.quantity * item.unitCost, sym)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>

            <div className="pt-3 border-t border-slate-200 flex items-center justify-between text-sm font-bold">
              <span>{tr(lang, 'Total PO Cost', 'إجمالي تكلفة أمر الشراء')}</span>
              <span className="font-mono tabular-nums">
                {formatCurrency(viewPO.totalCost, sym)}
              </span>
            </div>

            {viewPO.notes && (
              <p className="text-xs text-slate-600 bg-slate-50 p-3 rounded-lg border border-slate-200">
                {viewPO.notes}
              </p>
            )}
          </div>
        )}
      </Modal>

      {/* Add / Edit Supplier Modal */}
      <Modal
        open={supplierModalOpen}
        onClose={() => setSupplierModalOpen(false)}
        title={
          supplierForm.id
            ? tr(lang, 'Edit Supplier', 'تعديل بيانات المورد')
            : tr(lang, 'Add Supplier', 'إضافة مورد جديد')
        }
        footer={
          <>
            <button
              type="button"
              onClick={() => setSupplierModalOpen(false)}
              className="px-4 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg whitespace-nowrap"
            >
              {tr(lang, 'Cancel', 'إلغاء')}
            </button>
            <button
              type="submit"
              form="supplier-form"
              className="px-4 py-2 text-xs font-semibold text-white bg-teal-700 hover:bg-teal-800 rounded-lg whitespace-nowrap"
            >
              {tr(lang, 'Save Supplier', 'حفظ المورد')}
            </button>
          </>
        }
      >
        <form id="supplier-form" onSubmit={handleSaveSupplier} className="space-y-3.5">
          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              {tr(lang, 'Supplier Name *', 'اسم المورد *')}
            </label>
            <input
              type="text"
              required
              value={supplierForm.name}
              onChange={(e) => setSupplierForm({ ...supplierForm, name: e.target.value })}
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
            />
          </div>
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                {tr(lang, 'Contact Person', 'مسؤول التواصل')}
              </label>
              <input
                type="text"
                value={supplierForm.contactPerson}
                onChange={(e) =>
                  setSupplierForm({ ...supplierForm, contactPerson: e.target.value })
                }
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                {tr(lang, 'Phone', 'رقم الهاتف')}
              </label>
              <input
                type="text"
                dir="ltr"
                value={supplierForm.phone}
                onChange={(e) => setSupplierForm({ ...supplierForm, phone: e.target.value })}
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
              />
            </div>
          </div>
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                {tr(lang, 'Email', 'البريد الإلكتروني')}
              </label>
              <input
                type="email"
                dir="ltr"
                value={supplierForm.email}
                onChange={(e) => setSupplierForm({ ...supplierForm, email: e.target.value })}
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                {tr(lang, 'Opening Balance Owed', 'الرصيد الافتتاحي المستحق')} ({sym.trim()})
              </label>
              <input
                type="number"
                min={0}
                step="0.01"
                value={supplierForm.balanceOwed}
                onChange={(e) =>
                  setSupplierForm({ ...supplierForm, balanceOwed: e.target.value })
                }
                className="w-full px-3 py-2 text-sm font-mono border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
              />
            </div>
          </div>
          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              {tr(lang, 'Address', 'العنوان')}
            </label>
            <input
              type="text"
              value={supplierForm.address}
              onChange={(e) => setSupplierForm({ ...supplierForm, address: e.target.value })}
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
            />
          </div>
          {supplierSchema.length > 0 && (
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {supplierSchema.map((cf) => (
                <div key={cf.id}>
                  <label className="block text-xs font-medium text-slate-700 mb-1">
                    {cf.label}
                  </label>
                  <input
                    type={cf.type}
                    value={supplierForm.customFields[cf.key] ?? ''}
                    onChange={(e) =>
                      setSupplierForm((prev) => ({
                        ...prev,
                        customFields: { ...prev.customFields, [cf.key]: e.target.value },
                      }))
                    }
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
              ))}
            </div>
          )}
        </form>
      </Modal>

      {/* Record Supplier Payment Modal */}
      <Modal
        open={Boolean(paySupplierTarget)}
        onClose={() => setPaySupplierTarget(null)}
        title={tr(lang, 'Record Supplier Payment', 'تسجيل دفعة لمورد')}
        subtitle={paySupplierTarget?.name}
        maxWidthClass="max-w-sm"
        footer={
          <>
            <button
              type="button"
              onClick={() => setPaySupplierTarget(null)}
              className="px-4 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg whitespace-nowrap"
            >
              {tr(lang, 'Cancel', 'إلغاء')}
            </button>
            <button
              type="submit"
              form="supplier-pay-form"
              className="px-4 py-2 text-xs font-semibold text-white bg-teal-700 hover:bg-teal-800 rounded-lg whitespace-nowrap"
            >
              {tr(lang, 'Record Payment', 'تأكيد السداد')}
            </button>
          </>
        }
      >
        <form id="supplier-pay-form" onSubmit={handleRecordSupplierPay} className="space-y-4">
          <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg flex justify-between text-xs">
            <span className="text-slate-600">
              {tr(lang, 'Current Balance Owed', 'الرصيد المستحق حالياً')}
            </span>
            <span className="font-mono font-semibold text-amber-700">
              {formatCurrency(paySupplierTarget?.balanceOwed ?? 0, sym)}
            </span>
          </div>
          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              {tr(lang, 'Payment Amount', 'مبلغ السداد')} ({sym.trim()})
            </label>
            <input
              type="number"
              min={0.01}
              max={paySupplierTarget?.balanceOwed ?? undefined}
              step="0.01"
              required
              value={paySupplierAmount}
              onChange={(e) => setPaySupplierAmount(e.target.value)}
              className="w-full px-3 py-2 text-sm font-mono border border-slate-300 rounded-lg focus:outline-none focus:border-teal-600"
            />
          </div>
        </form>
      </Modal>

      {/* Import & Custom Format Modal (context-aware to active tab) */}
      <DataImportModal
        open={importModalOpen}
        onClose={() => setImportModalOpen(false)}
        moduleKey={activeTab === 'orders' ? 'purchases' : 'suppliers'}
        moduleLabel={
          activeTab === 'orders'
            ? tr(lang, 'Purchase Orders', 'أوامر الشراء')
            : tr(lang, 'Suppliers', 'الموردون')
        }
      />
    </div>
  );
};
